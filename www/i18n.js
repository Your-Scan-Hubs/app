let LANG = 'zh';
function detectLang() {
  const l = (navigator.language || '').toLowerCase();
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('ms') || l.startsWith('id')) return 'ms';
  return 'en';
}
function setLang(pref) {
  LANG = pref && STR[pref] ? pref : detectLang();
  document.documentElement.lang = { zh: 'zh-CN', en: 'en', ms: 'ms' }[LANG];
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.innerHTML = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
}
function t(key, vars) {
  const d = STR[LANG] || STR.zh;
  let s = (vars && vars.n === 1 && d[key + '1']) || d[key] || STR.zh[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}
